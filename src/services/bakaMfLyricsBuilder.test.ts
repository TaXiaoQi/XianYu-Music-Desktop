import { describe, expect, it } from 'vitest';

import { buildBakaMfLyricsRaw } from './bakaMfLyricsBuilder';

describe('buildBakaMfLyricsRaw', () => {
  it('将酷狗 KRC 逐字歌词转换为 Enhanced LRC', () => {
    const result = buildBakaMfLyricsRaw({
      lyric: '[0,420]周(0,52)杰(52,52)伦 (104,52)- (156,52)红(208,52)尘(260,52)客(312,52)栈(364,52)',
    });

    expect(result).toBe('[00:00.000]<00:00.000>周<00:00.052>杰<00:00.104>伦 <00:00.156>- <00:00.208>红<00:00.260>尘<00:00.312>客<00:00.364>栈<00:00.416>');
  });

  it('JOOX KRC 词偏移为绝对时间，词时间不再翻倍', () => {
    // JOOX 插件返回酷狗 KRC 格式，但词偏移是绝对时间（等于行时间戳），
    // 若按标准相对偏移计算会翻倍。检测到多数行首词偏移≈行时间戳即按绝对处理。
    const result = buildBakaMfLyricsRaw({
      lyric: [
        '[0,1000](0,677)你(677,677)還',
        '[8130,8370](8130,1626)詞(9756,1626)：(11382,1626)薛(13008,1626)之(14634,1626)謙',
      ].join('\n'),
    });

    expect(result).toBe(
      [
        '[00:00.000]<00:00.000>你<00:00.677>還<00:01.354>',
        '[00:08.130]<00:08.130>詞<00:09.756>：<00:11.382>薛<00:13.008>之<00:14.634>謙<00:16.260>',
      ].join('\n'),
    );
  });

  it('JOOX KRC 多行时仍能识别绝对偏移，不因全局正则 lastIndex 残留而漏判', () => {
    // 真实 JOOX 数据：每行首词偏移都等于行时间戳（绝对时间）。若检测循环复用
    // 全局正则 exec，lastIndex 会在行间残留，导致多数行取不到真正的首词偏移，
    // 对齐统计低于阈值而误判为相对偏移，词时间翻倍。
    const result = buildBakaMfLyricsRaw({
      lyric: [
        '[0,1000](0,640)有(640,640)何',
        '[5760,1000](5760,1440)詞(7200,1440)：(8640,1440)許(10080,1440)嵩',
        '[11530,1000](11530,1441)曲(12971,1441)：(14412,1441)許(15853,1441)嵩',
        '[23072,1000](23072,190)天(23270,220)空(23490,190)好(23680,190)想(23870,190)下(24060,190)雨',
        '[25132,1000](25132,190)我(25322,190)好(25512,190)想(25702,190)住(25892,190)你(26082,190)隔(26272,190)壁',
      ].join('\n'),
    });

    expect(result).toBe(
      [
        '[00:00.000]<00:00.000>有<00:00.640>何<00:01.280>',
        '[00:05.760]<00:05.760>詞<00:07.200>：<00:08.640>許<00:10.080>嵩<00:11.520>',
        '[00:11.530]<00:11.530>曲<00:12.971>：<00:14.412>許<00:15.853>嵩<00:17.294>',
        '[00:23.072]<00:23.072>天<00:23.270>空<00:23.490>好<00:23.680>想<00:23.870>下<00:24.060>雨<00:24.250>',
        '[00:25.132]<00:25.132>我<00:25.322>好<00:25.512>想<00:25.702>住<00:25.892>你<00:26.082>隔<00:26.272>壁<00:26.462>',
      ].join('\n'),
    );
  });

  it('标准酷狗 KRC（非零行时间的相对偏移）保持相对计算', () => {
    const result = buildBakaMfLyricsRaw({
      lyric: [
        '[10000,5000](0,500)你(500,500)好',
        '[16000,5000](0,500)我(500,500)好',
      ].join('\n'),
    });

    expect(result).toBe(
      [
        '[00:10.000]<00:10.000>你<00:10.500>好<00:11.000>',
        '[00:16.000]<00:16.000>我<00:16.500>好<00:17.000>',
      ].join('\n'),
    );
  });

  it('标准 lxlyric（首词偏移≈0）行时间戳保持不变', () => {
    const result = buildBakaMfLyricsRaw({
      lxlyric: '[00:10.000]<0,500>你<500,500>好',
    });

    expect(result).toBe('[00:10.000]<00:10.000>你<00:10.500>好<00:11.000>');
  });

  it('保留普通 LRC 歌词', () => {
    const result = buildBakaMfLyricsRaw({
      lyric: '[00:20.80]琴键上透着光',
    });

    expect(result).toBe('[00:20.80]琴键上透着光');
  });
});
